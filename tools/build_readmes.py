"""Builds topics/*/README.md from tools/topic_text.py + the real outputs. Run from repo root: python tools/build_readmes.py"""
import re, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(Path(__file__).parent))
from topic_text import T

def section(txt, prefix):
    m = re.search(r"={60}\n" + re.escape(prefix) + r"[^\n]*\n={60}\n(.*?)(?=\n={60}\n|\Z)", txt, re.S)
    return (m.group(0).split("\n", 3)[1] + "\n" + m.group(1)).strip() if m else ""

for i, (folder, (title, theory, math)) in enumerate(T.items(), 1):
    d = ROOT / "topics" / folder
    txt = (d / "outputs" / "results_python.txt").read_text(encoding="utf-8")
    worked = section(txt, "WORKED EXAMPLE") or section(txt, "WORKED EXAMPLES")
    interp = section(txt, "INTERPRETATION").split("\n", 1)[-1].strip()
    pngs = sorted(p.name for p in (d / "outputs").glob("*.png"))
    figs = "\n".join(f"![{p}](outputs/{p})" for p in pngs)
    first = f"{figs}"
    body = f"""# Topic {i}: {title}

**Course:** BIT 4131 Statistical Computing and Reporting

## 1. Theoretical explanation
{theory}

## 2. Mathematical formulation
{math}

## 3. Worked example
Hand-checkable example (full code in the scripts below).

```text
{worked}
```

## 4. Dataset analysis and implementation
| Language | Script | Console output |
|---|---|---|
| Python | [`python/analysis.py`](python/analysis.py) | [`outputs/results_python.txt`](outputs/results_python.txt) |
| R | [`r/analysis.R`](r/analysis.R) | [`outputs/results_r.txt`](outputs/results_r.txt) |

Datasets are in [`/data`](../../data) (reproducible synthetic data generated by `data/generate_datasets.py`, seed 4131).

## 5. Expected statistical output
See the two `results_*.txt` files above for the complete printed output (tables, test statistics, p-values, estimates).

## 6. Interpretation and visualisation
{interp}

### Figures
Files prefixed `py_` come from Python, `r_` from R.

{figs}
"""
    (d / "README.md").write_text(body, encoding="utf-8")
print("built", len(T), "READMEs")
