# Kaggle Heart Disease in R: CI (T5), tests (T6), bootstrap (T20), logistic regression (T18)
source("common/helpers.R"); start_topic("28_kaggle_heart_disease")
df <- load_data("kaggle/heart_disease.csv"); names(df)[1] <- "age"
h("DATASET: Kaggle Heart Disease (Cleveland, 303 patients; target as labelled by Kaggle)")
cat("NOTE: physiology suggests target=1 is the LOWER-risk group (higher max heart rate, less ST depression); the Kaggle description says target=1 = disease. Results follow the label as given.\n")
print(table(df$target))
h("CONFIDENCE INTERVALS (Topic 5)"); print(t.test(df$chol)$conf.int)
print(prop.test(sum(df$target), nrow(df), correct = FALSE)$conf.int)  # Wilson interval
h("HYPOTHESIS TESTS (Topic 6) + BOOTSTRAP (Topic 20): thalach by target")
a <- df$thalach[df$target == 1]; b <- df$thalach[df$target == 0]; tt <- t.test(a, b); print(tt)
diffs <- replicate(5000, mean(sample(a, replace = TRUE)) - mean(sample(b, replace = TRUE)))
cat(sprintf("Bootstrap 95%% CI for the difference = (%.1f, %.1f), SE = %.2f\n", quantile(diffs, .025), quantile(diffs, .975), sd(diffs)))
print(chisq.test(table(df$sex, df$target)))
h("LOGISTIC REGRESSION (Topic 18)")
m <- glm(target ~ age + factor(sex) + factor(cp) + trestbps + chol + thalach + factor(exang) + oldpeak, data = df, family = binomial); print(summary(m))
orr <- exp(cbind(OR = coef(m), suppressMessages(confint.default(m)))); cat("\nOdds ratios:\n"); print(round(orr, 3))
idx <- sample(nrow(df), .7 * nrow(df)); mt <- update(m, data = df[idx, ]); pr <- predict(mt, df[-idx, ], type = "response"); y <- df$target[-idx]; pred <- as.integer(pr > .5)
print(table(Actual = y, Predicted = pred)); r <- rank(pr); auc <- (sum(r[y == 1]) - sum(y == 1) * (sum(y == 1) + 1) / 2) / (sum(y == 1) * sum(y == 0))
cat(sprintf("Accuracy = %.3f, Recall = %.3f, AUC = %.3f\n", mean(pred == y), sum(pred == 1 & y == 1) / sum(y == 1), auc))
save_plot("heart_overview", {
  par(mfrow = c(1, 3)); hist(b, col = rgb(0, 0, 1, .5), main = "Max heart rate", xlab = "thalach", xlim = range(df$thalach)); hist(a, col = rgb(1, 0, 0, .5), add = TRUE)
  hist(diffs, col = "#33a02c", main = "Bootstrap: mean difference", xlab = ""); o <- order(pr, decreasing = TRUE)
  plot(c(0, cumsum(y[o] == 0) / sum(y == 0)), c(0, cumsum(y[o] == 1) / sum(y == 1)), type = "l", xlab = "FPR", ylab = "TPR", main = sprintf("ROC (AUC %.2f)", auc)); abline(0, 1, lty = 2)
}, width = 1500, height = 500)
h("INTERPRETATION")
cat(sprintf("- About %.0f%% of patients carry label target=1.\n", mean(df$target) * 100))
cat(sprintf("- target=1 patients reach a higher peak heart rate by %.1f bpm (p = %.1e); the bootstrap CI agrees with the t-test.\n", mean(a) - mean(b), tt$p.value))
cat(sprintf("- Each extra unit of ST depression multiplies the odds of target=1 by %.2f (below 1, consistent with target=1 being the lower-risk label).\n", orr["oldpeak", "OR"]))
cat(sprintf("- Held-out AUC %.2f.\n", auc))
end_topic()
