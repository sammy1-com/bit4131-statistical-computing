import base64
import io
import platform
import sys
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[3]))
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import scipy
import statsmodels
import statsmodels.formula.api as smf
from common.helpers import Report, load
from scipy import stats

R = Report(__file__)
SEED = 4131
np.random.seed(SEED)
df = load("students.csv")

R.h("WORKED EXAMPLE: the reproducibility checklist")
for item in ["Fixed random seed", "Raw data kept unchanged in data/", "All steps in code (no manual edits)",
             "Package versions recorded", "Outputs regenerated by one command", "Interpretation written next to results"]:
    R.p(" [x]", item)


def fig_to_b64(fig):
    buf = io.BytesIO(); fig.savefig(buf, format="png", dpi=110, bbox_inches="tight"); plt.close(fig)
    return base64.b64encode(buf.getvalue()).decode()


# ---- analysis ------------------------------------------------------------------------------------------
R.h("BUILDING THE REPORT")
desc = df[["study_hours", "attendance_pct", "sleep_hours", "prior_gpa", "exam_score"]].describe().T.round(2)
by_method = df.groupby("method").exam_score.agg(["count", "mean", "std"]).round(2)
model = smf.ols("exam_score ~ study_hours + attendance_pct + prior_gpa + C(method)", df).fit()
coef = pd.DataFrame({"estimate": model.params, "std_err": model.bse, "t": model.tvalues, "p_value": model.pvalues}).round(4)
a_, b_, c_ = [df[df.method == m].exam_score for m in "ABC"]
f_, p_ = stats.f_oneway(a_, b_, c_)
r_, rp_ = stats.pearsonr(df.study_hours, df.exam_score)

fig1, ax = plt.subplots(1, 2, figsize=(10, 3.8))
ax[0].hist(df.exam_score, bins=20, color="#9ecae1", edgecolor="white"); ax[0].set(title="Exam score distribution", xlabel="Score")
df.boxplot(column="exam_score", by="method", ax=ax[1], grid=False); ax[1].set(title="Score by method", xlabel="Method"); fig1.suptitle("")
fig2, ax2 = plt.subplots(figsize=(5.5, 3.8))
ax2.scatter(df.study_hours, df.exam_score, s=14, alpha=0.5)
b, a = np.polyfit(df.study_hours, df.exam_score, 1); xs = np.linspace(df.study_hours.min(), df.study_hours.max(), 20)
ax2.plot(xs, a + b * xs, "r"); ax2.set(title=f"Study hours vs score (r = {r_:.2f})", xlabel="Study hours", ylabel="Exam score")
img1, img2 = fig_to_b64(fig1), fig_to_b64(fig2)

md = f"""# Student Performance: A Reproducible Statistical Report

*Generated automatically on {date.today().isoformat()} with Python {platform.python_version()}, pandas {pd.__version__}, scipy {scipy.__version__}, statsmodels {statsmodels.__version__}. Random seed = {SEED}.*

## 1. Objective
Investigate which factors influence exam performance among {len(df)} students and whether teaching method matters.

## 2. Data
`data/students.csv` (synthetic, generated by `data/generate_datasets.py`). {df.shape[1]} variables, no missing values.

### Descriptive statistics
{desc.to_markdown()}

### Exam score by teaching method
{by_method.to_markdown()}

## 3. Methods
One-way ANOVA (method effect), Pearson correlation (study hours), and multiple linear regression (OLS) with study hours, attendance, prior GPA and method as predictors. Significance level 0.05.

## 4. Results
- **ANOVA:** F = {f_:.2f}, p = {p_:.2g}
- **Correlation (study hours, score):** r = {r_:.3f}, p = {rp_:.2g}
- **Regression:** R² = {model.rsquared:.3f}, adjusted R² = {model.rsquared_adj:.3f}

### Regression coefficients
{coef.to_markdown()}

## 5. Conclusions
1. Teaching method matters: mean scores differ significantly across methods (p = {p_:.2g}).
2. Study hours is the strongest single predictor (r = {r_:.2f}); each extra hour adds about {model.params['study_hours']:.2f} marks, controlling for the other factors.
3. The model explains {model.rsquared:.0%} of score variation; the remainder is individual variation not measured here.
4. The data are synthetic: conclusions illustrate the method, not real students.

## 6. Reproducibility
Run `python data/generate_datasets.py` then `python topics/23_reproducible_reporting/python/analysis.py`. Package versions are listed above.
"""
